const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { _electron } = require(process.env.JUANYE_PLAYWRIGHT || 'playwright');

async function main() {
  const root = path.resolve(__dirname, '..');
  const artifacts = path.join(root, 'artifacts/qa');
  fs.mkdirSync(artifacts, { recursive: true });
  const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'juanye-desktop-qa-'));
  const env = { ...process.env, JUANYE_TEST_USER_DATA: userData };
  delete env.ELECTRON_RUN_AS_NODE;
  const packaged = process.argv.includes('--packaged');
  const app = await _electron.launch({ executablePath: packaged ? path.join(root, 'release/win-unpacked/卷页.exe') : path.join(root, 'node_modules/electron/dist/electron.exe'), args: packaged ? [] : [root], env, timeout: 60000 });
  const errors = [];
  try {
    const page = await app.firstWindow();
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    await page.waitForSelector('.katex', { timeout: 30000 });
    await page.getByText('已保存', { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => window.juanye?.platform), 'win32');
    const marker = '本地保存校验：$\\frac{1}{2}$';
    await page.locator('textarea').first().fill(marker);
    await page.getByText('已保存', { exact: true }).waitFor();
    await page.reload();
    await page.waitForSelector('textarea');
    await page.waitForFunction(value => document.querySelector('textarea')?.value === value, marker);
    await page.waitForSelector('.katex .mfrac');
    await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, path.join(artifacts, 'desktop-smoke.pdf'));
    await page.getByRole('button', { name: '导出 PDF', exact: true }).click();
    await page.getByText('PDF 已导出', { exact: true }).waitFor({ timeout: 20000 });
    const pdf = fs.readFileSync(path.join(artifacts, 'desktop-smoke.pdf'));
    assert.equal(pdf.subarray(0, 4).toString(), '%PDF');
    assert.ok(pdf.length > 10000);
    await page.getByRole('button', { name: '历史记录', exact: true }).click();
    assert.ok(await page.getByText('最近保存').count());
    await page.getByRole('complementary').getByRole('button', { name: '关闭', exact: true }).click();
    const config = await page.evaluate(() => window.juanye.getModel());
    assert.equal(config.hasKey, false);
    assert.ok(!Object.hasOwn(config, 'key'));
    const testKey = 'local-test-credential-not-a-real-api-key';
    await page.evaluate(async ({ config, testKey }) => { await window.juanye.saveModel({ ...config, key: testKey }); }, { config, testKey });
    assert.equal((await page.evaluate(() => window.juanye.getModel())).hasKey, true);
    assert.ok(!fs.readFileSync(path.join(userData, 'model.json'), 'utf8').includes(testKey));
    await page.keyboard.press('Control+k');
    await page.getByRole('button').filter({ hasText: '一图多题识别' }).first().click();
    await page.getByRole('dialog').locator('input[type=file]').setInputFiles(path.join(artifacts, 'desktop-smoke.pdf'));
    await page.getByText('0/3 页 · 0 道题', { exact: true }).waitFor({ timeout: 15000 });
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('button', { name: '外观', exact: true }).click();
    await page.locator('label').filter({ has: page.getByRole('radio', { name: /Telegram/ }) }).click();
    assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'telegram');
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
    await page.reload();
    await page.waitForSelector('textarea');
    assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'telegram');
    await page.screenshot({ path: path.join(artifacts, 'electron-telegram.png') });
    assert.deepEqual(errors, []);
    const draft = JSON.parse(fs.readFileSync(path.join(userData, 'draft.json'), 'utf8'));
    assert.equal(draft.exam.sections[0].questions[0].stem, marker);
    assert.ok(draft.history.length >= 2);
    const result = { passed: true, errors, pdfBytes: pdf.length, snapshots: draft.history.length, userData, cloudRequests: 0 };
    fs.writeFileSync(path.join(artifacts, 'electron-results.json'), JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result));
  } finally { await app.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
