const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const asar = require('@electron/asar');
const root = path.resolve(__dirname, '..');
const archive = path.join(root, 'release/win-unpacked/resources/app.asar');
const version = require(path.join(root, 'package.json')).version;
assert.equal(JSON.parse(asar.extractFile(archive, 'package.json').toString()).version, version);
const html = fs.readFileSync(path.join(root, 'dist/index.html'));
assert.ok(asar.extractFile(archive, path.join('dist', 'index.html')).equals(html));
const pages = fs.readdirSync(path.join(root, 'dist')).filter(name => name.endsWith('.html'));
for (const page of pages) assert.ok(asar.extractFile(archive, path.join('dist', page)).equals(fs.readFileSync(path.join(root, 'dist', page))), `Stale release HTML entry: ${page}`);
const referenced = [...html.toString().matchAll(/(?:src|href)="([^"?#]+\.(?:js|css))"/g)].map(match => match[1].replace(/^\.\//, ''));
const chunks = fs.readdirSync(path.join(root, 'dist/assets')).filter(name => /\.(?:js|mjs|css)$/.test(name)).map(name => `assets/${name}`);
const assets = [...new Set([...referenced, ...chunks])];
for (const asset of assets) assert.ok(asar.extractFile(archive, path.join('dist', ...asset.split('/'))).equals(fs.readFileSync(path.join(root, 'dist', asset))), `Stale release asset: ${asset}`);
const backend = fs.readdirSync(path.join(root, 'electron')).filter(name => /\.(?:cjs|mjs)$/.test(name) && !name.endsWith('.test.cjs'));
for (const name of backend) assert.ok(asar.extractFile(archive, path.join('electron', name)).equals(fs.readFileSync(path.join(root, 'electron', name))), `Stale release backend: ${name}`);
console.log(JSON.stringify({ version, latestBuildInRelease: true, assetsMatch: true, checkedHtmlEntries: pages.length, checkedAssets: assets.length, checkedBackendModules: backend.length }));
